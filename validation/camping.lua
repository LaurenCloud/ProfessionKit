-- Exercise grouped recipe browsing through the complete addon in a fresh client session.
local harness, addon = Harness, ProfessionKitAddon
local UI = addon.UI
harness.Event("ADDON_LOADED", "ProfessionKit")
harness.Item(279972, "Faction Banner", 0, 0, 10000)
harness.Recipe(1229504, 197, "Faction Banner", 279972, 3, 25, 1, {{2996, 1}, {2320, 1}}, 2717)
addon.Open(197); harness.Advance(1)
harness.Check("Camping classification uses the client category, not the recipe name", addon.Client.Recipe(1229504).isCamping and not addon.Client.Recipe(3755).isCamping)
harness.Check("Regular recipes precede camping in Skill-ups", UI.rows[#UI.rows].id == 1229504 and not UI.selectedRecipe.isCamping)
UI.priceSort:Click()
harness.Check("Even the highest-value camping batch stays below all regular recipes", UI.rows[#UI.rows].id == 1229504 and UI.rows[#UI.rows].batchPrice > UI.rows[1].batchPrice and not UI.selectedRecipe.isCamping)
UI.list:Run("OnMouseWheel", -30)
harness.Check("Scrolling reveals a separate Camping heading", UI.recipeHeadings.Camping:IsShown() and UI.recipeHeadings.Camping:GetText() == "Camping")
local _, _, _, _, firstRowTop = UI.recipeButtons[1]:GetPoint()
local _, _, _, _, secondRowTop = UI.recipeButtons[2]:GetPoint()
harness.Check("Price rows have room for two lines while gaps stay six units", firstRowTop - secondRowTop - UI.recipeButtons[1]:GetHeight() == 6 and UI.recipeButtons[1]:GetHeight() == 58)
local lastButton = UI.recipeButtons[UI.visibleRecipeCount]
local _, _, _, _, lastRowTop = lastButton:GetPoint()
harness.Check("Section headings and last recipe fit inside the list", UI.list:GetHeight() == -lastRowTop + lastButton:GetHeight() + 12 and UI.frame:GetHeight() <= UIParent:GetHeight() - 60)
harness.Snapshot("tailoring-camping-section")
lastButton:Click()
addon.Refresh()
harness.Check("Explicit camping selection survives inventory refresh", UI.selectedRecipe.id == 1229504)
harness.Snapshot("tailoring-connected-camping")
UI.list:Run("OnMouseWheel", 30)
local visibleConnectors = 0
for _, button in ipairs(UI.recipeButtons) do if button.connector:IsVisible() then visibleConnectors = visibleConnectors + 1 end end
harness.Check("Scrolling the selected recipe away hides its connector and preserves details", visibleConnectors == 0 and UI.selectedRecipe.id == 1229504)
UI.search:SetText("Camping")
addon.state.selected = nil; UI.RefreshList()
harness.Check("Camping-only search automatically selects its first recipe", #UI.rows == 1 and UI.selectedRecipe.id == 1229504 and UI.recipeHeadings.Camping:IsShown() and not UI.recipeHeadings.Recipes:IsShown())
UI.search:SetText("bag")
harness.Check("Regular-only search removes the unused Camping heading", #UI.rows == 1 and UI.selectedRecipe.id == 3755 and not UI.recipeHeadings.Camping:IsShown())
UI.search:SetText("no matches")
harness.Check("Empty search hides all headings and the pin control", #UI.rows == 0 and not UI.selectedRecipe and not UI.pinRecipe:IsShown()
    and not UI.recipeHeadings.Recipes:IsShown() and not UI.recipeHeadings.Camping:IsShown() and not UI.recipeHeadings.Pinned:IsShown())
UI.search:SetText("")
UI.multiplyByQuantity:Click()
harness.Check("Per-craft ranking retains regular-first ordering", UI.rows[#UI.rows].isCamping and not UI.selectedRecipe.isCamping)

-- Reproduce the zero-Copper, craftable-Lodestone case.
harness.Item(279960, "Lodestone", 0, 0, 2000)
harness.Item(2835, "Rough Stone", 2, 7, 3)
harness.Recipe(1230161, 186, "Lodestone", 279960, 3, 25, 1, {{2835, 1}, {2840, 1}}, 2717)
harness.recipes[2659], harness.recipes[3304] = nil, nil
harness.inventory[2770] = 0
addon.Open(186); harness.Advance(1)
harness.Check("Unavailable Copper remains the default above craftable camping gear", UI.rows[1].id == 2657 and UI.rows[2].id == 1230161 and UI.rows[2].available == 7 and UI.selectedRecipe.id == 2657)
harness.Snapshot("mining-camping-section")
UI.search:SetText("Lodestone")
harness.Check("A camping-only recipe search selects its first recipe", #UI.rows == 1 and UI.selectedRecipe.id == 1230161)
UI.search:SetText("")
addon.state.selected = nil; UI.RefreshList()
harness.Check("Restoring mixed results defaults back to regular crafting", UI.selectedRecipe.id == 2657)
UI.skillSort:Click()
UIParent:SetSize(1024, 768)
addon.Open(197); harness.Advance(1)
UI.list:Run("OnMouseWheel", -30)
harness.Check("Grouped scrolling fits a smaller display and reaches camping", UI.frame:GetHeight() <= 708 and UI.recipeButtons[UI.visibleRecipeCount].recipe.id == 1229504)
harness.Snapshot("tailoring-camping-small-screen")

UI.recipeButtons[UI.visibleRecipeCount]:Click()
UI.pinRecipe:Click()
harness.Check("Pinning the last Camping row brings the same selection into view at the top", UI.recipeScrollOffset == 0 and UI.rows[1].id == 1229504
    and UI.selectedRecipe.id == 1229504 and UI.pinRecipe.label:GetText() == "Unpin" and UI.recipeHeadings.Pinned:IsShown() and not UI.recipeHeadings.Camping:IsShown())
UI.search:SetText("Camping")
harness.Check("A pinned Camping recipe still matches its category once", #UI.rows == 1 and UI.rows[1].section == "Pinned" and not UI.recipeHeadings.Camping:IsShown())
UI.search:SetText("Linen Bag")
UI.pinRecipe:Click()
UI.search:SetText("Red Linen Robe")
UI.pinRecipe:Click()
UI.search:SetText("")
addon.Refresh()
harness.Check("Pinned skill ranking mixes regular and Camping recipes", #UI.rows == 14 and UI.rows[1].id == 3755 and UI.rows[2].id == 2389
    and UI.rows[3].id == 1229504 and UI.rows[4].section == "Recipes")
UI.priceSort:Click()
harness.Check("Per-craft Prices ranks Camping first when its value wins within Pinned", UI.rows[1].id == 1229504 and UI.rows[2].id == 2389 and UI.rows[3].id == 3755)
UI.multiplyByQuantity:Click()
harness.Check("Quantity-weighted Prices reorders pins by batch value", UI.rows[1].id == 1229504 and UI.rows[2].id == 3755 and UI.rows[3].id == 2389)
UI.search:SetText("Faction Banner")
UI.pinRecipe:Click()
UI.search:SetText("")
harness.Check("Unpinning returns a Camping recipe to its group and preserves selection", UI.rows[#UI.rows].id == 1229504 and UI.rows[#UI.rows].section == "Camping"
    and UI.selectedRecipe.id == 1229504 and UI.pinRecipe.label:GetText() == "Pin" and not ProfessionKitDB.pinnedRecipes[1229504])
UI.list:Run("OnMouseWheel", -30)
harness.Check("Three groups still scroll to the last recipe on a small screen", UI.recipeButtons[UI.visibleRecipeCount].recipe.id == 1229504
    and UI.recipeHeadings.Camping:IsShown() and UI.frame:GetHeight() <= 708)
UI.search:SetText("Linen Bag")
UI.pinRecipe:Click()
harness.Check("Unpinned regular recipe returns to Recipes", #UI.rows == 1 and UI.rows[1].section == "Recipes" and not UI.recipeHeadings.Pinned:IsShown())
UI.search:SetText("")
UI.list:Run("OnMouseWheel", 30)
UI.recipeButtons[1]:Click()
harness.Snapshot("tailoring-pinned-recipes")
